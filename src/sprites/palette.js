// 渲染助手:把字符 grid 转为像素数据
export function rasterize(grid, W = 64, H = 64) {
  const pixels = [];
  for (let r = 0; r < H; r++) {
    const row = grid[r] || '';
    for (let c = 0; c < W; c++) {
      const ch = row[c];
      if (!ch || ch === '.') continue;
      const color = PALETTE[ch];
      if (!color) continue;
      pixels.push({ x: c, y: r, color });
    }
  }
  return pixels;
}
