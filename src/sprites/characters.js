const W = 64, H = 64;
const E = '.'.repeat(W); // 空行

// 工具:把稀疏定义转成完整 64×64 grid
function buildGrid(rowsMap) {
  const g = Array(H).fill(E);
  for (const [r, content] of Object.entries(rowsMap)) {
    const row = content.padEnd(W, '.').slice(0, W);
    g[parseInt(r)] = row;
  }
  return g;
}

